@app.post("/predict", response_model=SinglePredictionResponse, tags=["Inference"])
def predict_single(req: SinglePredictionRequest):
    """Executes single record inference through the full trained pipeline."""
    bundle = get_model_bundle()
    pipeline = bundle["pipeline"]
    problem_spec = bundle["problem_spec"]

    # Convert single feature dict to 1-row DataFrame
    input_df = pd.DataFrame([req.features])

    try:
        raw_pred = pipeline.predict(input_df)[0]
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Inference error with provided features: {str(e)}"
        )

    prob = None
    probs_dict = None

    if problem_spec.is_classification and hasattr(pipeline, "predict_proba"):
        try:
            proba_arr = pipeline.predict_proba(input_df)[0]
            if len(proba_arr) == 2:
                prob = float(proba_arr[1])
            else:
                prob = float(np.max(proba_arr))

            if bundle.get("classes") and len(bundle["classes"]) == len(proba_arr):
                probs_dict = {
                    str(cls_name): float(p)
                    for cls_name, p in zip(bundle["classes"], proba_arr)
                }
        except Exception:
            pass

    # Map numeric prediction back to class name if classes are available
    final_pred = raw_pred
    if problem_spec.is_classification and bundle.get("classes"):
        try:
            cls_idx = int(raw_pred)
            if 0 <= cls_idx < len(bundle["classes"]):
                final_pred = bundle["classes"][cls_idx]
        except (ValueError, TypeError):
            pass

    if isinstance(final_pred, (np.integer, np.floating)):
        final_pred = final_pred.item()

    return SinglePredictionResponse(
        status="success",
        prediction=final_pred,
        probability=prob,
        probabilities=probs_dict,
        problem_type=problem_spec.problem_type.value,
    )


@app.post("/predict/batch", response_model=BatchPredictionResponse, tags=["Inference"])
def predict_batch(req: BatchPredictionRequest):
    """Executes batch inference on a list of input records."""
    if not req.records:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Records list is empty."
        )

    bundle = get_model_bundle()
    pipeline = bundle["pipeline"]
    problem_spec = bundle["problem_spec"]

    input_df = pd.DataFrame(req.records)

    try:
        raw_preds = pipeline.predict(input_df)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Batch inference failed: {str(e)}"
        )

    probs = None
    if problem_spec.is_classification and hasattr(pipeline, "predict_proba"):
        try:
            prob_arr = pipeline.predict_proba(input_df)
            if prob_arr.shape[1] == 2:
                probs = [float(p[1]) for p in prob_arr]
            else:
                probs = [float(np.max(p)) for p in prob_arr]
        except Exception:
            probs = None

    # Map back to classes if classification
    final_preds = []
    for p in raw_preds:
        mapped = p
        if problem_spec.is_classification and bundle.get("classes"):
            try:
                idx = int(p)
                if 0 <= idx < len(bundle["classes"]):
                    mapped = bundle["classes"][idx]
            except (ValueError, TypeError):
                pass
        if isinstance(mapped, (np.integer, np.floating)):
            mapped = mapped.item()
        final_preds.append(mapped)

    return BatchPredictionResponse(
        status="success",
        count=len(final_preds),
        predictions=final_preds,
        probabilities=probs,
    )
